class CppBackend:
    def __init__(self):
        self.loop_id = 0
        self.function_names: set[str] = set()

    def expr(self, node: dict) -> str:
        kind, fields, line = node["kind"], node["fields"], node["line"]
        if kind == "Literal":
            value = fields["value"]
            if value is None: return "Value()"
            if isinstance(value, bool): return f"Value({'true' if value else 'false'})"
            if isinstance(value, (int, float)): return f"Value(pcSafe(\"literal\", static_cast<double>({repr(value)}), {line}))"
            if isinstance(value, str): return "Value(std::string(" + json.dumps(value, ensure_ascii=False) + "))"
            raise CppBackendError(f"baris {line}: literal tidak didukung")
        if kind == "Variable": return f"env->get({json.dumps(fields['name'], ensure_ascii=False)}, {line})"
        if kind == "List": return "pcList({" + ", ".join(self.expr(x) for x in fields["items"]) + "})"
        if kind == "Dict":
            pairs = ["std::make_pair(" + self.expr(pair[0]) + ", " + self.expr(pair[1]) + ")" for pair in fields["items"]]
            return "pcDict({" + ", ".join(pairs) + "})"
        if kind == "Index": return f"pcIndex({self.expr(fields['collection'])}, {self.expr(fields['index'])}, {line})"
        if kind == "Unary": return f"pcUnary({json.dumps(fields['op'])}, {self.expr(fields['value'])}, {line})"
        if kind == "Binary":
            op = fields["op"]
            left, right = self.expr(fields["left"]), self.expr(fields["right"])
            if op == "dan": return f"pcAnd([&]() {{ return {left}; }}, [&]() {{ return {right}; }})"
            if op == "atau": return f"pcOr([&]() {{ return {left}; }}, [&]() {{ return {right}; }})"
            return f"pcBinary({json.dumps(op)}, {left}, {right}, {line})"
        if kind == "Call":
            args = ", ".join(self.expr(x) for x in fields["args"])
            return f"pcCall({json.dumps(fields['name'], ensure_ascii=False)}, std::vector<Value>{{{args}}}, env, {line})"
        raise CppBackendError(f"baris {line}: ekspresi belum didukung: {kind}")

    def block(self, nodes: list[dict], indent: str, in_function: bool = False) -> list[str]:
        out: list[str] = []
        for node in nodes:
            kind, fields, line = node["kind"], node["fields"], node["line"]
            if kind == "Function":
                if not in_function: continue
                raise CppBackendError(f"baris {line}: fungsi hanya boleh di tingkat teratas")
            out.append(indent + f"pcStep({line});")
            if kind == "Declare":
                out.append(indent + f'env->define({json.dumps(fields["name"], ensure_ascii=False)}, {self.expr(fields["value"])}, {line});')
            elif kind == "Assign":
                out.append(indent + f'env->set({json.dumps(fields["name"], ensure_ascii=False)}, {self.expr(fields["value"])}, {line});')
            elif kind == "Print":
                out.append(indent + f"pcOut({self.expr(fields['value'])});")
            elif kind == "Expr":
                out.append(indent + f"(void)({self.expr(fields['value'])});")
            elif kind == "IndexAssign":
                out.append(indent + f"pcSetIndex({self.expr(fields['collection'])}, {self.expr(fields['index'])}, {self.expr(fields['value'])}, {line});")
            elif kind == "If":
                out.append(indent + f"if (pcTruthy({self.expr(fields['condition'])})) {{")
                out.extend(self.block(fields["then_body"], indent + "    ", in_function))
                if fields["else_body"]:
                    out.append(indent + "} else {")
                    out.extend(self.block(fields["else_body"], indent + "    ", in_function))
                out.append(indent + "}")
            elif kind == "While":
                out.append(indent + f"while (pcTruthy({self.expr(fields['condition'])})) {{")
                out.append(indent + f"    pcStep({line});")
                out.extend(self.block(fields["body"], indent + "    ", in_function))
                out.append(indent + "}")
            elif kind == "For":
                self.loop_id += 1
                item = f"pcItem{self.loop_id}"
                out.append(indent + f"for (const auto& {item} : pcIter({self.expr(fields['iterable'])}, {line})) {{")
                out.append(indent + f"    pcStep({line});")
                out.append(indent + f'env->loopVar({json.dumps(fields["name"], ensure_ascii=False)}, {item}, {line});')
                out.extend(self.block(fields["body"], indent + "    ", in_function))
                out.append(indent + "}")
            elif kind == "Return":
                if not in_function: raise CppBackendError(f"baris {line}: balek hanya boleh di dalam fungsi")
                value = fields["value"]
                out.append(indent + ("return Value();" if value is None else "return " + self.expr(value) + ";"))
            elif kind in {"Input", "Try"}:
                raise CppBackendError(f"baris {line}: fitur belum didukung backend C++: {kind}")
            else:
                raise CppBackendError(f"baris {line}: pernyataan belum didukung: {kind}")
        return out

    def generate(self, document: dict) -> str:
        validate(document)
        root = document["program"]
        body = root["fields"]["body"]
        functions = [item for item in body if item["kind"] == "Function"]
        for item in functions:
            fields, line = item["fields"], item["line"]
            name, params = fields["name"], fields["params"]
            if name in self.function_names: raise CppBackendError(f"baris {line}: fungsi duplikat: {name}")
            if name in BUILTIN_NAMES: raise CppBackendError(f"baris {line}: nama fungsi bentrok dengan builtin: {name}")
            if not isinstance(params, list) or len(set(params)) != len(params):
                raise CppBackendError(f"baris {line}: parameter fungsi tidak valid")
            self.function_names.add(name)
        unsupported = []
        stack = [root]
        top_level_ids = {id(item) for item in functions}
        while stack:
            item = stack.pop()
            if isinstance(item, dict) and "kind" in item:
                if item["kind"] not in SUPPORTED: unsupported.append((item.get("line", 1), item["kind"]))
                if item["kind"] == "Function" and id(item) not in top_level_ids:
                    unsupported.append((item.get("line", 1), "nested Function"))
                stack.extend(item.get("fields", {}).values())
            elif isinstance(item, dict): stack.extend(item.values())
            elif isinstance(item, list): stack.extend(item)
        if unsupported:
            line, kind = unsupported[0]
            raise CppBackendError(f"baris {line}: node belum didukung backend C++: {kind}")

        prototypes = []
        function_code = []
        registration = []
        dispatch = []
        for item in functions:
            fields, line = item["fields"], item["line"]
            name, params = fields["name"], fields["params"]
            prototypes.append(f"static Value pcFn_{name}(const std::vector<Value>& args, std::shared_ptr<Env> closure, int callLine);")
            dispatch.append(
                f'    if (name == {json.dumps(name, ensure_ascii=False)}) {{ '
                f'auto fn = std::get<Value::FunctionPtr>(env->get(name, line).data); '
                f'return pcFn_{name}(args, fn->closure, line); }}'
            )
            registration.append(
                f'env->define({json.dumps(name, ensure_ascii=False)}, '
                f'Value(std::make_shared<PCFunction>(PCFunction{{{json.dumps(name, ensure_ascii=False)}, '
                f'{{{", ".join(json.dumps(p, ensure_ascii=False) for p in params)}}}, env}})), {line});'
            )
            function_code.append(f"static Value pcFn_{name}(const std::vector<Value>& args, std::shared_ptr<Env> closure, int callLine) {{")
            function_code.append(f'    pcArity({json.dumps(name, ensure_ascii=False)}, args, {len(params)}, {len(params)}, callLine);')
            function_code.append("    auto env = std::make_shared<Env>(closure);")
            for i, param in enumerate(params):
                function_code.append(f'env->define({json.dumps(param, ensure_ascii=False)}, args[{i}], callLine);')
            function_code.extend(self.block(fields["body"], "    ", True))
            function_code.append("    return Value();")
            function_code.append("}")
            function_code.append("")

        main_body = "\n".join(self.block([node for node in body if node["kind"] != "Function"], "        "))
        runtime = RUNTIME.replace("__FUNCTION_PROTOTYPES__", "\n".join(prototypes))
        runtime = runtime.replace("__FUNCTION_DISPATCH__", "\n".join(dispatch))
        runtime = runtime.replace("__FUNCTION_REGISTRATION__", "\n        ".join(registration))
        runtime = runtime.replace("__MAIN_BODY__", main_body)
        return runtime + "\n" + "\n".join(function_code) + "\n"


def generate(document: dict) -> str:
    return CppBackend().generate(document)


def compile_source(source: str, source_name: str = "<memory>") -> str:
    return generate(from_source(source, source_name))


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Kompilasi subset PusingCuk menjadi source C++17.")
    parser.add_argument("source", help="berkas sumber .cuk")
    parser.add_argument("-o", "--output", help="berkas source C++ tujuan; default stdout")
    args = parser.parse_args(argv)
    try:
        path = Path(args.source)
        result = compile_source(path.read_text(encoding="utf-8"), path.name)
        if args.output: Path(args.output).write_text(result, encoding="utf-8")
        else: sys.stdout.write(result)
        return 0
    except (OSError, UnicodeError, ValueError, TypeError, RecursionError) as exc:
        print(f"Kesalahan backend C++: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
