def _node(value, expected=None):
    if not isinstance(value, dict) or not {"kind", "fields", "line"} <= set(value):
        raise JSBackendError("node IR tidak valid")
    kind = value["kind"]
    if kind not in SUPPORTED:
        raise JSBackendError(f"fitur {kind!r} belum didukung backend JavaScript")
    if expected and kind not in expected:
        raise JSBackendError(f"node {kind!r} tidak valid pada posisi ini")
    return kind, value["fields"], value["line"]


def _js_literal(value, line):
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int) and not isinstance(value, bool) and abs(value) > 9007199254740991:
        raise JSBackendError(f"baris {line}: integer di luar rentang aman JavaScript")
    if isinstance(value, (int, float)):
        if isinstance(value, float) and not (value == value and abs(value) != float("inf")):
            raise JSBackendError(f"baris {line}: literal angka non-finite tidak didukung")
        return json.dumps(value, allow_nan=False)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    raise JSBackendError(f"baris {line}: literal {type(value).__name__} tidak didukung")


def generate(document: dict, as_module: bool = False) -> str:
    validate(document)
    root_kind, root_fields, root_line = _node(document["program"], {"Program"})
    body = root_fields.get("body")
    if not isinstance(body, list):
        raise JSBackendError(f"baris {root_line}: Program.body harus berupa daftar")

    functions = {}
    for statement in body:
        kind, fields, line = _node(statement)
        if kind == "Function":
            name, params = fields.get("name"), fields.get("params")
            if not isinstance(name, str) or not IDENTIFIER.fullmatch(name):
                raise JSBackendError(f"baris {line}: nama fungsi tidak valid")
            if name in BUILTIN_NAMES or name in functions:
                raise JSBackendError(f"baris {line}: nama fungsi {name!r} sudah digunakan")
            if not isinstance(params, list) or any(
                not isinstance(p, str) or not IDENTIFIER.fullmatch(p) for p in params
            ) or len(set(params)) != len(params):
                raise JSBackendError(f"baris {line}: parameter fungsi tidak valid")
            functions[name] = statement

    if as_module:
        if not functions:
            raise JSBackendError("modul JavaScript membutuhkan setidaknya satu fungsi")
        if any(statement["kind"] != "Function" for statement in body):
            raise JSBackendError("mode modul hanya menerima deklarasi fungsi tingkat teratas")

    def expr(node, names):
        kind, f, line = _node(node)
        if kind == "Literal":
            return _js_literal(f.get("value"), line)
        if kind == "Variable":
            name = f.get("name")
            if name not in names:
                raise JSBackendError(f"baris {line}: variabel {name!r} belum dideklarasikan")
            return names[name]
        if kind == "List":
            return "[" + ", ".join(expr(v, names) for v in f.get("items", [])) + "]"
        if kind == "Dict":
            pairs = []
            for pair in f.get("items", []):
                if not isinstance(pair, list) or len(pair) != 2:
                    raise JSBackendError(f"baris {line}: pasangan kamus IR tidak valid")
                pairs.append(f"[{expr(pair[0], names)}, {expr(pair[1], names)}]")
            return "new Map([" + ", ".join(pairs) + "])"
        if kind == "Index":
            return f"pcGet({expr(f.get('collection'), names)}, {expr(f.get('index'), names)})"
        if kind == "Call":
            name, args = f.get("name"), f.get("args")
            rendered = ", ".join(expr(arg, names) for arg in args)
            builtin = JS_BUILTINS.get(name)
            if builtin is not None:
                if not builtin["min_args"] <= len(args) <= builtin["max_args"]:
                    low, high = builtin["min_args"], builtin["max_args"]
                    expected = str(low) if low == high else f"{low}-{high}"
                    raise JSBackendError(f"baris {line}: {name}() membutuhkan {expected} argumen")
                return f"{builtin['helper']}({rendered})"
            if name not in functions:
                raise JSBackendError(f"baris {line}: fungsi {name!r} tidak dikenal atau belum didukung")
            expected = len(functions[name]["fields"]["params"])
            if len(args) != expected:
                raise JSBackendError(f"baris {line}: fungsi {name!r} membutuhkan {expected} argumen")
            return f"pc_fn_{name}({rendered})"
        if kind == "Unary":
            value = expr(f.get("value"), names)
            op = f.get("op")
            if op == "bukan": return f"(!pcTruthy({value}))"
            if op == "-": return f"pcNeg({value})"
            raise JSBackendError(f"baris {line}: operator unary {op!r} belum didukung")
        if kind == "Binary":
            op = f.get("op")
            left, right = expr(f.get("left"), names), expr(f.get("right"), names)
            if op == "+": return f"pcAdd({left}, {right})"
            if op == "-": return f"pcSub({left}, {right})"
            if op == "*": return f"pcMul({left}, {right})"
            if op == "/": return f"pcDiv({left}, {right})"
            if op == "//": return f"pcFloorDiv({left}, {right})"
            if op == "%": return f"pcMod({left}, {right})"
            if op in {"==", "!="}:
                eq = f"pcEq({left}, {right})"
                return eq if op == "==" else f"(!{eq})"
            if op in {"<", "<=", ">", ">="}:
                return f"pcCompare({left}, {right}, {json.dumps(op)})"
            if op == "dan": return f"(pcTruthy({left}) && pcTruthy({right}))"
            if op == "atau": return f"(pcTruthy({left}) || pcTruthy({right}))"
            raise JSBackendError(f"baris {line}: operator {op!r} belum didukung")
        raise JSBackendError(f"baris {line}: ekspresi {kind!r} belum didukung")

    def statements(items, names, indent="  ", in_function=False, in_loop=False):
        output = []
        for statement in items:
            kind, f, line = _node(statement)
            if kind == "Function":
                raise JSBackendError(f"baris {line}: fungsi hanya boleh di tingkat teratas")
            if kind == "Declare":
                name = f.get("name")
                if not isinstance(name, str) or not IDENTIFIER.fullmatch(name):
                    raise JSBackendError(f"baris {line}: nama variabel tidak valid")
                if name in names:
                    raise JSBackendError(f"baris {line}: variabel {name!r} sudah dideklarasikan")
                if in_loop:
                    raise JSBackendError(f"baris {line}: deklarasi lah di dalam loop belum didukung; deklarasikan sebelum loop")
                js_name = f"pc_v_{name}"
                value = expr(f.get("value"), names)
                names[name] = js_name
                output.append(f"{indent}let {js_name} = {value};")
            elif kind == "Input":
                name = f.get("name")
                if not isinstance(name, str) or not IDENTIFIER.fullmatch(name):
                    raise JSBackendError(f"baris {line}: nama variabel input tidak valid")
                if name in names:
                    raise JSBackendError(f"baris {line}: variabel {name!r} sudah dideklarasikan")
                prompt = expr(f.get("prompt"), names)
                names[name] = f"pc_v_{name}"
                output.append(f"{indent}let {names[name]} = pcInput({prompt});")
            elif kind == "Assign":
                name = f.get("name")
                if name not in names:
                    raise JSBackendError(f"baris {line}: variabel {name!r} belum dideklarasikan")
                output.append(f"{indent}{names[name]} = {expr(f.get('value'), names)};")
            elif kind == "Print":
                output.append(f"{indent}pcOut({expr(f.get('value'), names)});")
            elif kind == "If":
                condition = expr(f.get("condition"), names)
                output.append(f"{indent}if (pcTruthy({condition})) {{")
                output.extend(statements(f.get("then_body", []), dict(names), indent + "  ", in_function, in_loop) or [indent + "  ;"])
                if f.get("else_body"):
                    output.append(f"{indent}}} else {{")
                    output.extend(statements(f["else_body"], dict(names), indent + "  ", in_function, in_loop) or [indent + "  ;"])
                output.append(f"{indent}}}")
            elif kind == "While":
                condition = expr(f.get("condition"), names)
                output.append(f"{indent}{{ let pc_loop_count = 0; while (pcTruthy({condition})) {{")
                output.append(f"{indent}  if (++pc_loop_count > 10000) throw new Error('batas iterasi loop terlampaui');")
                output.extend(statements(f.get("body", []), names, indent + "  ", in_function, True) or [indent + "  ;"])
                output.append(f"{indent}}} }}")
            elif kind == "For":
                name, iterable = f.get("name"), expr(f.get("iterable"), names)
                if not isinstance(name, str) or not IDENTIFIER.fullmatch(name):
                    raise JSBackendError(f"baris {line}: nama variabel loop tidak valid")
                if name in names:
                    raise JSBackendError(f"baris {line}: variabel loop {name!r} sudah digunakan")
                js_name = f"pc_v_{name}"
                loop_names = dict(names)
                loop_names[name] = js_name
                output.append(f"{indent}{{ let pc_loop_count = 0; for (let {js_name} of pcIter({iterable})) {{")
                output.append(f"{indent}  if (++pc_loop_count > 10000) throw new Error('batas iterasi loop terlampaui');")
                output.extend(statements(f.get("body", []), loop_names, indent + "  ", in_function, True) or [indent + "  ;"])
                output.append(f"{indent}}} }}")
            elif kind == "IndexAssign":
                output.append(f"{indent}pcSet({expr(f.get('collection'), names)}, {expr(f.get('index'), names)}, {expr(f.get('value'), names)});")
            elif kind == "Return":
                if not in_function:
                    raise JSBackendError(f"baris {line}: balek hanya boleh di dalam fungsi")
                value = f.get("value")
                output.append(f"{indent}return {expr(value, names) if value is not None else 'null'};")
            elif kind == "Try":
                body, handler_name = f.get("body", []), f.get("handler_name")
                handler, final = f.get("handler", []), f.get("final", [])
                if handler_name is not None and (
                    not isinstance(handler_name, str) or not IDENTIFIER.fullmatch(handler_name)
                ):
                    raise JSBackendError(f"baris {line}: nama variabel ketangkep tidak valid")
                if handler_name is None and not final:
                    output.extend(statements(body, names, indent, in_function, in_loop))
                    continue
                output.append(f"{indent}try {{")
                output.extend(statements(body, dict(names), indent + "  ", in_function, in_loop) or [indent + "  ;"])
                if handler_name is not None:
                    error_name = f"pc_error_{line}"
                    catch_name = f"pc_catch_{handler_name}_{line}"
                    handler_names = dict(names)
                    handler_names[handler_name] = catch_name
                    output.append(f"{indent}}} catch ({error_name}) {{")
                    output.append(f"{indent}  const {catch_name} = String({error_name} && {error_name}.message !== undefined ? {error_name}.message : {error_name});")
                    output.extend(statements(handler, handler_names, indent + "  ", in_function, in_loop) or [indent + "  ;"])
                if final:
                    output.append(f"{indent}}} finally {{")
                    output.extend(statements(final, dict(names), indent + "  ", in_function, in_loop) or [indent + "  ;"])
                output.append(f"{indent}}}")
            else:
                raise JSBackendError(f"baris {line}: pernyataan {kind!r} belum didukung backend JavaScript")
        return output

    output = [JS_RUNTIME, ""]
    for name, statement in functions.items():
        f, line = statement["fields"], statement["line"]
        names = {}
        params = []
        for param in f["params"]:
            names[param] = f"pc_v_{param}"
            params.append(names[param])
        output.append(f"function pc_fn_{name}({', '.join(params)}) {{")
        output.extend(statements(f["body"], names, "  ", in_function=True) or ["  ;"])
        output.append("}")
        output.append("")
    if as_module:
        exports = ", ".join(
            f"{json.dumps(name)}: pc_fn_{name}" for name in functions
        )
        output.append(f"const pcApi = Object.freeze({{ {exports} }});")
        output.append("if (typeof module === \"object\" && module.exports) module.exports = pcApi;")
        output.append("if (typeof globalThis === \"object\") globalThis.PusingCukAccountingRules = pcApi;")
    else:
        output.append("// Program utama")
        output.extend(statements([s for s in body if s["kind"] != "Function"], {}) or [";"])
    return "\n".join(output) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description="Kompilasi PusingCuk ke JavaScript untuk Node.js.")
    parser.add_argument("file", help="berkas sumber .pusingcuk")
    parser.add_argument("-o", "--output", help="berkas .js tujuan; default stdout")
    parser.add_argument(
        "--module", action="store_true",
        help="hasilkan modul fungsi yang dapat dipanggil dari JavaScript/browser",
    )
    args = parser.parse_args(argv)
    path = Path(args.file)
    if not path.is_file():
        print(f"Kesalahan: berkas tidak ditemukan: {path}", file=sys.stderr)
        return 2
    try:
        js = generate(from_source(path.read_text(encoding="utf-8"), path.name), as_module=args.module)
        if args.output:
            Path(args.output).write_text(js, encoding="utf-8")
        else:
            sys.stdout.write(js)
    except (SyntaxError, ValueError, TypeError, OSError) as exc:
        print(f"Kesalahan kompilasi JavaScript: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
