#!/usr/bin/env python3
"""PVM v1 binary reader and Python 3 source transpiler; standard library only."""
import pathlib, re, sys
def read_pvm(filename):
    data=pathlib.Path(filename).read_bytes()
    if len(data)<6 or data[:4]!=b"PVM1" or int.from_bytes(data[4:6],"little")!=1: raise ValueError("header PVM tidak valid/versi tidak didukung")
    out=[]; i=6
    while i<len(data):
        if i+5>len(data): raise ValueError("record PVM terpotong")
        op=data[i]; n=int.from_bytes(data[i+1:i+5],"little"); i+=5
        if n>1048576 or i+n>len(data): raise ValueError("panjang payload tidak valid")
        out.append((op,data[i:i+n].decode("utf-8"))); i+=n
    return out
def pyexpr(s):
    s=s.strip()
    s=re.sub(r"\bbenar\b","True",s); s=re.sub(r"\bsalah\b","False",s)
    s=re.sub(r"\bdan\b","and",s); s=re.sub(r"\batau\b","or",s); s=re.sub(r"\bbukan\b","not",s)
    s=re.sub(r"\bpanjang\s*\(","len(",s)
    return s
def compile_pvm(records):
    out=["# Generated by PusingCuk PVM v1 backend.","import pathlib, sys, urllib.request, urllib.parse, json","v={}","__opened=None","def __eval(s):","    safe={'len':len,'abs':abs,'min':min,'max':max,'round':round}","    return eval(s, {'__builtins__':{} , **safe}, v)","def __fetch(url):","    url=str(url)","    if url.startswith('data:text/plain,'): return urllib.parse.unquote(url[len('data:text/plain,'):])","    with urllib.request.urlopen(url,timeout=10) as response: return response.read().decode('utf-8')","def main():","    global __opened"]
    indent=1; blocks=[]
    def emit(s): out.append("    "*indent+s)
    def val(s): return "__eval("+repr(pyexpr(s))+")"
    for op,raw in records:
        a=raw.strip(); m=None
        if op==1: emit("print("+val(a)+")")
        elif op==2:
            m=re.match(r"^([A-Za-z_]\w*)\s*=\s*(.*)$",a)
            if m: emit("v["+repr(m.group(1))+"]="+val(m.group(2)))
            elif a: emit("v["+repr(a)+"]=None")
        elif op==3: emit("if "+val(a)+":"); blocks.append("if"); indent+=1
        elif op==4:
            if blocks and blocks[-1]=="if": indent-=1; emit("else:"); indent+=1
            else: emit("pass # kampret tanpa njir")
        elif op==5: emit("while "+val(a)+":"); blocks.append("mumet"); indent+=1
        elif op==6:
            m=re.match(r"^([A-Za-z_]\w*)\s+(?:dalam|in)\s+(.+)$",a)
            if m: emit("for __item in "+val(m.group(2))+":"); indent+=1; emit("v["+repr(m.group(1))+"]=__item"); blocks.append("for")
        elif op==7:
            m=re.match(r"^([A-Za-z_]\w*)\s*=\s*(.*)$",a)
            if m: emit("v["+repr(m.group(1))+"]=input("+val(m.group(2) or "''")+")")
        elif op==8: emit("raise NotImplementedError('OP_FUNGSI belum didukung oleh backend PVM v1')")
        elif op==9: emit("return "+val(a or "None"))
        elif op==10: emit("__opened=open("+val(a)+",'a+',encoding='utf-8')")
        elif op==11:
            m=re.match(r"^([A-Za-z_]\w*)\s+(?:dari|from)\s+(.+)$",a)
            if m: emit("v["+repr(m.group(1))+"]=pathlib.Path("+val(m.group(2))+").read_text(encoding='utf-8')")
            else: emit("print(pathlib.Path("+val(a)+").read_text(encoding='utf-8'))")
        elif op==12: emit("pathlib.Path("+val(a)+").unlink(missing_ok=True)")
        elif op==13:
            if a in ("njir","mumet","untuk","for") and blocks: indent=max(1,indent-1); blocks.pop()
            elif a=="buka": emit("__opened.close() if __opened is not None else None"); emit("__opened=None")
        elif op==14: emit("v['__gerombolan']="+val(a))
        elif op==15: emit("v['__petik']="+val(a))
        elif op==16:
            m=re.match(r"^([A-Za-z_]\w*)\s*,\s*(.+)$",a)
            if m: emit("v.setdefault("+repr(m.group(1))+",[]).append("+val(m.group(2))+")")
            else: emit("raise ValueError('cemplungin perlu: nama_list, nilai')")
        elif op==17:
            m=re.match(r"^([A-Za-z_]\w*)\s*=\s*(.+)$",a)
            if m: emit("v["+repr(m.group(1))+"]=len("+val(m.group(2))+")")
            else: emit("print(len("+val(a)+"))")
        elif op==18:
            m=re.match(r"^([A-Za-z_]\w*)\s*=\s*(.+)$",a)
            if m: emit("v["+repr(m.group(1))+"]=__fetch("+val(m.group(2))+")")
            else: emit("print(__fetch("+val(a)+"))")
        elif op==19: emit("print(json.dumps("+val(a)+",ensure_ascii=False,indent=2))")
        else: raise ValueError("opcode tidak dikenal: "+str(op))
    while indent>1: indent-=1; emit("pass # tutup blok implisit")
    out += ["if __name__=='__main__':","    try: main()","    except Exception as exc:","        print('PVM runtime:',exc,file=sys.stderr)","        sys.exit(1)",""]
    return "\n".join(out)
def main():
    if len(sys.argv) not in (2,3): raise SystemExit("pakai: python compiler.py input.pvm [output.py]")
    result=compile_pvm(read_pvm(sys.argv[1]))
    if len(sys.argv)==3: pathlib.Path(sys.argv[2]).write_text(result,encoding="utf-8")
    else: sys.stdout.write(result)
if __name__=="__main__":
    try: main()
    except Exception as exc: print("pvm-python:",exc,file=sys.stderr); sys.exit(1)
